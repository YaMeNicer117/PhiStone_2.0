SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_INPUT_FILE = SCRIPT_DIR / "activity_mic_level.xlsx"
DEFAULT_OUTPUT_FILE = SCRIPT_DIR / "activity_mic_level_mean.xlsx"
DEFAULT_ERROR_LOG_FILE = SCRIPT_DIR / "activity_mic_level_error_log.csv"
DEFAULT_OUTLIER_LOG_FILE = SCRIPT_DIR / "activity_mic_level_outlier_log.csv"

DEFAULT_HEADER_SCAN_ROWS = 50
ORDINARY_ACTIVITY_RANGE_THRESHOLD = Decimal("0.6")
REFERENCE_ACTIVITY_GAP_THRESHOLD = Decimal("0.4")
REFERENCE_COMPOUND_ENTRY_THRESHOLD = 8
ACTIVITY_LEVEL_MIN = 0.0
ACTIVITY_LEVEL_MAX = 1.0
MAX_HEADER_COLUMNS = 256
MAX_XLSX_ROWS = 1_048_576
MAX_DATA_ROWS_PER_SHEET = MAX_XLSX_ROWS - 1

SMILES_HEADER = "SMILES"
ACTIVITY_LEVEL_HEADER = "Activity Level"
OUTPUT_HEADERS = ("Compound ID", "Canonical SMILES", "Mean Activity Level")
OUTLIER_LOG_HEADERS = (
    "Canonical SMILES",
    "Sheet",
    "Row",
    "Activity Level",
    "Minimum Activity Level",
    "Maximum Activity Level",
    "Activity Level Range",
    "Reason",
)


class ProcessingError(Exception):
    """Raised for a controlled input, validation, or output error."""


@dataclass(frozen=True)
class SheetColumns:
    header_row: int
    smiles_column: int
    activity_column: int


@dataclass(frozen=True)
class ActivityObservation:
    activity_level: Decimal
    sheet_name: str
    row_number: int


@dataclass
class CompoundAggregate:
    compound_id: int
    canonical_smiles: str
    occurrence_count: int = 0
    observations: list[ActivityObservation] = field(default_factory=list)
    retained_observations: list[ActivityObservation] = field(default_factory=list)
    discarded: bool = False

    def add_occurrence(
        self,
        observation: ActivityObservation | None,
    ) -> None:
        self.occurrence_count += 1
        if observation is not None:
            self.observations.append(observation)

    @property
    def mean_activity_level(self) -> float | None:
        values = self.retained_observations
        if not values:
            return None
        activity_sum = sum(
            (item.activity_level for item in values),
            Decimal(0),
        )
        return float(activity_sum / len(values))


@dataclass
class RunStats:
    worksheets_processed: int = 0
    rows_scanned: int = 0
    nonempty_smiles_rows: int = 0
    blank_smiles_rows: int = 0
    blank_activity_rows: int = 0
    activity_values_used: int = 0
    activity_values_retained: int = 0
    activity_values_discarded: int = 0
    ordinary_activity_values_discarded: int = 0
    compounds_without_activity_discarded: int = 0
    reference_compounds_preserved: int = 0
    reference_activity_values_discarded: int = 0


def progress_items(items, label: str, total: int | None = None, unit: str = "条"):
    """按完成数量显示进度，不预先读取或复制迭代器内容。"""
    if total is None:
        try:
            total = len(items)
        except TypeError:
            pass
    started = monotonic()
    last_refresh = started
    completed = 0
    previous_width = 0

    def display():
        nonlocal previous_width
        elapsed = monotonic() - started
        if total is None or completed > total:
            progress = f"已处理 {completed} {unit}"
        else:
            fraction = completed / total if total else 1.0
            filled = int(24 * fraction)
            remaining = f"{elapsed / completed * (total - completed):.0f}s" if completed else "--"
            progress = (
                f"[{'#' * filled}{'-' * (24 - filled)}] {fraction:6.1%} "
                f"{completed}/{total} {unit} 剩余约 {remaining}"
            )
        message = f"{label} {progress} 已用 {elapsed:.0f}s"
        print("\r" + message.ljust(previous_width), end="", file=sys.stderr, flush=True)
        previous_width = len(message)

    display()
    try:
        for item in items:
            yield item
            completed += 1
            now = monotonic()
            if now - last_refresh >= 0.25:
                display()
                last_refresh = now
    finally:
        display()
        print(file=sys.stderr, flush=True)


@contextmanager
def timed_stage(label: str):
    """无法取得准确百分比的操作显示动态状态和真实耗时。"""
    started = monotonic()
    stopped = Event()

    def animate():
        index = 0
        while not stopped.wait(0.25):
            symbol = "|/-\\"[index % 4]
            print(
                f"\r[{symbol}] {label}，已用 {monotonic() - started:.0f}s",
                end="", file=sys.stderr, flush=True,
            )
            index += 1

    print(f"[开始] {label}", file=sys.stderr, flush=True)
    worker = Thread(target=animate, daemon=True)
    worker.start()
    status = "中断"
    try:
        yield
        status = "完成"
    finally:
        stopped.set()
        worker.join()
        print(
            f"\r[{status}] {label}，耗时 {monotonic() - started:.1f}s",
            file=sys.stderr, flush=True,
        )


