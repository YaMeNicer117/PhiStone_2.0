"""Deduplicate SMILES and average filtered discrete activity levels.

The default input is the workbook generated by ``standardize_mic_level.py``.
All worksheets are processed in workbook order. RDKit canonical isomeric
SMILES are used as compound keys, so equivalent SMILES notations are merged
while distinct stereochemistry remains separate.

Blank Activity Level rows are skipped before SMILES parsing; blank SMILES rows
are also skipped. For two valid measurements, a span of at least 0.6 retains
only the higher value; otherwise both are averaged. For three to eight valid
measurements, repeatedly remove one extreme from the less populated nonempty
side of the current median while the span is at least 0.6. If one side is empty,
remove from the other side. Equal counts remove the extreme farther from the
median, preferring removal of the lower value when distances are equal.
The remaining measurements are averaged. Compounds with more than eight valid
measurements are treated as reference compounds: measurements at least 0.4
below the group maximum are removed before averaging.
"""

